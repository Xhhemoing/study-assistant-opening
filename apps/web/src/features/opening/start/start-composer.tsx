"use client";

import type { ReactNode } from "react";
import { ArrowRight, FilePlus2, GraduationCap, History, Search } from "lucide-react";
import { TransitionLink as Link } from "../v3/motion/view-transition";
import { KNOWLEDGE_HOME_HREF, LEARNING_HOME_HREF } from "../shell/destinations";

export type StartSuggestion = { id: string; label: string; meta?: string; href: string };
export type StartConfiguration = {
  greeting: string;
  /** 一句副标题：说明可以从哪里开始，不承诺 AI 已做过什么。 */
  subtitle?: string;
  /** 输入框上方的一张下一步卡（来自已保存记录）；没有时不占位。 */
  lead?: ReactNode;
  suggestions: StartSuggestion[];
  examples?: string[];
};

/** 助理首页的快捷动作：只指向已存在的规范页面，菜单不是唯一入口。 */
const QUICK_ACTIONS = [
  { label: "去学习", href: LEARNING_HOME_HREF, Icon: GraduationCap },
  { label: "写笔记", href: `${KNOWLEDGE_HOME_HREF}/new`, Icon: FilePlus2 },
  { label: "搜索", href: "/opening/search", Icon: Search },
  { label: "全部讨论", href: "/opening/assistant", Icon: History },
] as const;

/** Suggestions are supplied from saved records, never generated by a model. */
export function StartSuggestions({ suggestions, examples = [], onExample, objectHref = href => href }: Omit<StartConfiguration, "greeting" | "subtitle" | "lead"> & { onExample: (text: string) => void; objectHref?: (href: string) => string }) {
  return <div className="space-y-5 px-1 pt-4">
    {suggestions.length ? <ul aria-label="接下来" className="divide-y divide-line overflow-hidden rounded-tile border border-line bg-surface">
      {suggestions.slice(0, 3).map(item => <li key={item.id}>
        <Link href={objectHref(item.href)} className="group flex min-h-11 items-center justify-between gap-3 px-4 py-2.5 text-ui text-text transition-colors hover:bg-surface-2 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-inset focus-visible:ring-focus-ring">
          <span className="min-w-0 truncate">{item.label}{item.meta ? <span className="ml-2 text-meta text-text-2">{item.meta}</span> : null}</span>
          <ArrowRight size={15} aria-hidden="true" className="shrink-0 text-text-3 transition-transform group-hover:translate-x-0.5 group-hover:text-text motion-reduce:transition-none" />
        </Link>
      </li>)}
    </ul> : examples.length ? <ul aria-label="可以这样问" className="flex flex-wrap gap-2">
      {examples.map(example => <li key={example}><button type="button" onClick={() => onExample(example)} className="min-h-11 rounded-pill border border-line bg-surface/60 px-3 text-meta text-text-2 transition-colors hover:border-line-strong hover:text-text focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-focus-ring">{example}</button></li>)}
    </ul> : null}
    <nav aria-label="快捷开始" className="flex flex-wrap gap-1.5">
      {QUICK_ACTIONS.map(({ label, href, Icon }) => <Link key={href} href={objectHref(href)} className="inline-flex min-h-9 items-center gap-1.5 rounded-pill px-3 text-meta text-text-2 transition-colors hover:bg-text/5 hover:text-text focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-focus-ring">
        <Icon size={14} aria-hidden="true" />{label}
      </Link>)}
    </nav>
  </div>;
}
