import { readFile } from "node:fs/promises";
import path from "node:path";
import { expect, test } from "./fixtures";
import { loginOpeningOwner, seedOpeningOwner } from "./opening-auth";

test.skip(process.env.OPENING_E2E !== "1", "requires the isolated Opening configuration and fixture provider");
test.beforeAll(async () => { await seedOpeningOwner(); });
test("real upload and PDF parser feed cited tutor transport, then survive an in-flight refresh (fixture model)", async ({ browser, baseURL }, testInfo) => {
  const context = await browser.newContext({ baseURL });
  try {
    await loginOpeningOwner(context.request, baseURL!);
    const page = await context.newPage();
    const errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto("/opening/assistant");
    await expect(page).toHaveURL(/\/opening\/today\?ai=1$/);
    const assistant = page.getByRole("dialog", { name: "学习助手", exact: true });
    await expect(assistant).toBeVisible();
    const fixture = path.resolve("tests/fixtures/opening/parser-two-page.pdf");
    await assistant.getByRole("button", { name: "选择参考材料", exact: true }).click();
    await assistant.locator('#exploration-context input[type="file"]').setInputFiles(fixture);
    const uploaded = assistant.getByRole("list", { name: "助手上传队列", exact: true }).getByRole("listitem").filter({ hasText: "parser-two-page.pdf" });
    await expect(uploaded).toBeVisible();
    // No reload or direct DB write is allowed to make the source become selectable.
    const choice = assistant.getByRole("checkbox", { name: /parser-two-page.pdf/ });
    await expect(choice).toBeVisible({ timeout: 120_000 });
    await choice.check();
    await assistant.getByLabel("当前物理页码").fill("1");
    await assistant.getByRole("button", { name: "关闭上下文", exact: true }).click();
    await assistant.getByLabel("消息输入").fill("Summarize the selected page.");
    const submitted = page.waitForResponse((response) => response.url().endsWith("/api/opening/turns") && response.request().method() === "POST");
    await assistant.getByRole("button", { name: "发送", exact: true }).click();
    const accepted = await submitted;
    expect(accepted.status()).toBe(201);
    await page.reload();
    await expect(assistant.getByRole("log").getByText("[测试模型] 已收到原件第一页文本 page one。", { exact: true })).toBeVisible({ timeout: 45_000 });
    await assistant.getByRole("button", { name: "选择参考材料", exact: true }).click();
    await expect(choice).toBeChecked();
    await expect(assistant.getByLabel("当前物理页码")).toHaveValue("1");
    await assistant.getByRole("button", { name: "关闭上下文", exact: true }).click();
    const citation = assistant.getByRole("log").locator('a[href^="/opening/library?tab=materials&source="][href$="&version=0&page=1"]').first();
    await expect(citation).toHaveAccessibleName("来源 [1]：parser-two-page.pdf · 第 1 页");
    await expect(citation).toHaveAttribute("href", /\/opening\/library\?tab=materials&source=[0-9a-f-]+&version=0&page=1$/);
    await citation.click();
    const reader = page.getByRole("dialog", { name: "parser-two-page.pdf", exact: true });
    await expect(reader).toBeVisible();
    await reader.getByRole("button", { name: "提取文字 / OCR 核对", exact: true }).click();
    const readingTools = page.getByRole("dialog", { name: "提取文字 / OCR 核对", exact: true });
    await expect(readingTools.getByRole("region", { name: "解析正文", exact: true }).getByText(/Opening parser page one/)).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("reader-desktop-text.png"), fullPage: true });
    const desktopViewport = page.viewportSize()!;
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(readingTools.getByRole("region", { name: "解析正文", exact: true }).getByText(/Opening parser page one/)).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("reader-mobile-text.png"), fullPage: true });
    await readingTools.getByRole("button", { name: "关闭学习工具", exact: true }).click();
    await page.setViewportSize(desktopViewport);
    await reader.getByText("原件与处理信息", { exact: true }).click();
    const original = reader.getByRole("link", { name: "打开原件 · 第 1 页", exact: true });
    await expect(original).toHaveAttribute("href", /\/api\/opening\/sources\/[0-9a-f-]+\/download\?version=0#page=1$/);
    const bytes = await context.request.get((await original.getAttribute("href"))!);
    expect(bytes.status()).toBe(200);
    expect(bytes.headers()["x-opening-source-version"]).toBe("0");
    expect(await bytes.body()).toEqual(await readFile(fixture));
    await reader.getByRole("button", { name: "返回", exact: true }).click();
    await expect(reader).not.toBeVisible();
    const providerStats = async () => (await context.request.get("http://127.0.0.1:18081/stats")).json();
    // Suggestions run in their own durable job after the one completed answer.
    await expect.poll(providerStats).toEqual({ calls: 2, answerCalls: 1, metadataCalls: 1 });
    await page.reload();
    await expect(assistant.getByRole("log").getByText("Summarize the selected page.", { exact: true })).toHaveCount(1);
    await expect(assistant.getByRole("log").getByText("[测试模型] 已收到原件第一页文本 page one。", { exact: true })).toHaveCount(1);
    expect(await providerStats()).toEqual({ calls: 2, answerCalls: 1, metadataCalls: 1 });
    expect(errors).toEqual([]);
    await page.screenshot({ path: testInfo.outputPath("workflow-desktop.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(assistant.getByLabel("消息输入")).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("workflow-mobile.png"), fullPage: true });
  } finally { await context.close(); }
});
